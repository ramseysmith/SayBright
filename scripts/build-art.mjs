// Turns design/art/*.svg (the editable source) into src/components/art/CategoryIcon.tsx.
// Run after editing any glyph: node scripts/build-art.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../design/art/', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort();
const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const tagMap = { path: 'Path', circle: 'Circle', rect: 'Rect', line: 'Line' };

const glyphs = files.map((f) => {
  const name = f.replace('.svg', '');
  const body = readFileSync(new URL(f, dir), 'utf8').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const els = [...body.matchAll(/<(path|circle|rect|line)\s([^>]*?)\/>/g)].map(([, tag, attrs]) => {
    const props = [...attrs.matchAll(/([a-z-]+)="([^"]*)"/g)]
      .map(([, k, v]) => {
        if (v === 'currentColor') return `${camel(k)}={color}`;
        if (/^-?[\d.]+$/.test(v) && k !== 'd') return `${camel(k)}={${v}}`;
        return `${camel(k)}="${v}"`;
      })
      .join(' ');
    return `<${tagMap[tag]} ${props} />`;
  });
  return `    case '${name}':\n      return (\n        <>\n          ${els.join('\n          ')}\n        </>\n      );`;
});

const out = `// Generated by scripts/build-art.mjs from design/art. Edit the SVGs, then rerun.
import React from 'react';
import Svg, { Circle, Line, Path, Rect } from 'react-native-svg';

export const CATEGORY_GLYPHS = [${files.map((f) => `'${f.replace('.svg', '')}'`).join(', ')}] as const;

function Glyph({ name, color }: { name: string; color: string }) {
  switch (name) {
${glyphs.join('\n')}
    default:
      return <Circle cx={16} cy={16} r={10} stroke={color} />;
  }
}

/** One glyph per affirmation category, on a 32 point grid with a 1.8 stroke. */
export default function CategoryIcon({ name, size = 24, color }: { name: string; size?: number; color: string }) {
  return (
    <Svg width={size} height={size} viewBox="0 0 32 32" fill="none" stroke={color} strokeWidth={1.8} strokeLinecap="round" strokeLinejoin="round">
      <Glyph name={name} color={color} />
    </Svg>
  );
}

// Keep unused imports referenced for families that add rect or line glyphs later
void Rect;
void Line;
`;
writeFileSync(new URL('../src/components/art/CategoryIcon.tsx', import.meta.url), out);
console.log('wrote CategoryIcon.tsx with', files.length, 'glyphs');
